export function findBase(id: string) {
  return catalog.bases.find((b) => b.id === id) ?? catalog.bases[0]
}
export function findSauce(id: string) {
  return catalog.sauces.find((s) => s.id === id)
}
export function findTopping(id: string) {
  return catalog.toppings.find((t) => t.id === id)
}
export function findFilling(id: string | null) {
  return id ? catalog.fillings.find((f) => f.id === id) : undefined
}
export function findExtra(id: string) {
  return catalog.extras.find((e) => e.id === id)
}
